# PlatformIO pre-script (env s06_load): writes src/s06/build_id_gen.h with the git commit of this
# checkout, whether the tree is dirty, and the env name (spec S06 v3.4 Z21, L7-23: #fw line,
# #run_start). Only s06_load.c includes the header, so a new commit rebuilds one file.
# The header is in .gitignore, so writing it does not make the tree dirty.
import os
import subprocess

Import("env")  # noqa: F821  (PlatformIO SCons)

root = env.subst("$PROJECT_DIR")  # noqa: F821


def git(*args):
    try:
        return subprocess.run(["git", "-C", root] + list(args), capture_output=True, text=True,
                              check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None


sha = (git("rev-parse", "--short=12", "HEAD") or "unknown").strip()
status = git("status", "--porcelain")
if status is None:
    dirty = 1
else:
    changed = [l[3:] for l in status.splitlines() if l[3:] and not l[3:].startswith(".vscode/")]
    dirty = 1 if changed else 0
pioenv = env["PIOENV"]  # noqa: F821

text = ("// Generated by scripts/build_id.py at build time; do not edit, not in git.\n"
        "#pragma once\n"
        f'#define FW_GIT_SHA   "{sha}"\n'
        f"#define FW_GIT_DIRTY {dirty}\n"
        f'#define FW_ENV       "{pioenv}"\n')
path = os.path.join(root, "src", "s06", "build_id_gen.h")
old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
if old != text:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
print(f"build_id: {sha} dirty={dirty} env={pioenv}")
