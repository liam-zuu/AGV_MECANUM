# PlatformIO pre-script, every env (base env esp32-s3-devkitc-1; first for s06_load, spec S06 v3.4 Z21,
# L7-23): writes the git commit of this checkout, whether the tree is dirty and the env name to
#   src/fw_id_gen.h        for every firmware: boot line "#fw sha=.. dirty=.. env=.." and the UDP
#                          line "#fw,sha=..,dirty=..,env=.." (main.c, logger.c; Liam 09/11, CODE)
#   src/s06/build_id_gen.h the same text, kept for s06_load.c
# Both headers are in .gitignore, so writing them does not make the tree dirty. A header is rewritten
# only when its text changes, so a new commit rebuilds only the files that include it.
import os
import subprocess

Import("env")  # noqa: F821  (PlatformIO SCons)

root = env.subst("$PROJECT_DIR")  # noqa: F821


def git(*args):
    try:
        return subprocess.run(["git", "-C", root] + list(args), capture_output=True, text=True,
                              check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None


sha = (git("rev-parse", "--short=12", "HEAD") or "unknown").strip()
status = git("status", "--porcelain")
if status is None:
    dirty = 1
else:
    changed = [l[3:] for l in status.splitlines() if l[3:] and not l[3:].startswith(".vscode/")]
    dirty = 1 if changed else 0
pioenv = env["PIOENV"]  # noqa: F821

text = ("// Generated by scripts/build_id.py at build time; do not edit, not in git.\n"
        "#pragma once\n"
        f'#define FW_GIT_SHA   "{sha}"\n'
        f"#define FW_GIT_DIRTY {dirty}\n"
        f'#define FW_ENV       "{pioenv}"\n')
for path in (os.path.join(root, "src", "fw_id_gen.h"), os.path.join(root, "src", "s06", "build_id_gen.h")):
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
print(f"build_id: {sha} dirty={dirty} env={pioenv}")
